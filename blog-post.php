      <p style="font-size:1.0625rem;color:var(--text-secondary);line-height:1.85;margin-bottom:20px;">In 1990, there were fewer than a dozen families left in Jaipur still practising authentic Blue Pottery — a craft that had survived Mughal emperors, colonial rule, partition and two world wars. The killer? Cheap plastic.</p>
      <p style="font-size:1.0625rem;color:var(--text-secondary);line-height:1.85;margin-bottom:20px;">Blue Pottery arrived in Jaipur with Persian craftsmen in the 17th century. It's unique because it uses no clay from the earth — instead, artisans work with a compound of quartz stone powder, powdered glass, Multani mitti (Fuller's earth), borax, gum and water. The result is a characteristically translucent, slightly porous ceramic with that iconic blue-and-white colour palette.</p>
      <blockquote style="border-left:4px solid var(--saffron);padding:16px 20px;background:var(--saffron-pale);border-radius:0 var(--r-md) var(--r-md) 0;font-style:italic;font-size:1.125rem;color:var(--text-secondary);line-height:1.7;margin:28px 0;">"When a Blue Pottery family stops, the knowledge dies with them. This isn't like a recipe you can write down. It lives in the hands." — Rajan Kumhar, Master Potter</blockquote>
      <p style="font-size:1.0625rem;color:var(--text-secondary);line-height:1.85;margin-bottom:20px;">The craft got its GI (Geographical Indication) tag in 2008, which helped — but not enough. The real change came when platforms like Conscious Indi connected Jaipur's remaining pottery families directly with consumers willing to pay genuine artisan prices.</p>
      <p style="font-size:1.0625rem;color:var(--text-secondary);line-height:1.85;">Today, there are around 30 active Blue Pottery families in Jaipur. That's up from fewer than 10 in 2000. It's not a recovery — but it's a holding pattern, and with the right support, it could become a revival.</p>
