CREATE TABLE IF NOT EXISTS `influencer_packages` (
  `id` CHAR(36) NOT NULL PRIMARY KEY,
  `influencer_id` CHAR(36) NOT NULL,
  `title` VARCHAR(160) NOT NULL,
  `description` VARCHAR(3000) NOT NULL,
  `price_inr` DECIMAL(12,2) NOT NULL,
  `deliverables_json` JSON NOT NULL,
  `platforms_json` JSON NOT NULL,
  `turnaround_days` SMALLINT UNSIGNED NOT NULL,
  `revisions` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `usage_rights` VARCHAR(1000) NOT NULL,
  `vendor_requirements` VARCHAR(1000) NOT NULL,
  `capacity` SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  `tax_treatment` VARCHAR(160) NOT NULL,
  `cancellation_terms` VARCHAR(1000) NOT NULL,
  `status` VARCHAR(24) NOT NULL DEFAULT 'draft',
  `reviewed_by` CHAR(36) NULL,
  `reviewed_at` DATETIME NULL,
  `review_note` VARCHAR(500) NULL,
  `created_at` DATETIME NOT NULL,
  `updated_at` DATETIME NOT NULL,
  INDEX `idx_influencer_packages_public` (`status`,`price_inr`),
  INDEX `idx_influencer_packages_owner` (`influencer_id`,`created_at`),
  CONSTRAINT `fk_influencer_packages_owner` FOREIGN KEY (`influencer_id`) REFERENCES `influencers`(`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
