CREATE TABLE IF NOT EXISTS customer_return_review_flags (
  id CHAR(36) NOT NULL PRIMARY KEY,
  customer_id CHAR(36) NOT NULL,
  scope_key VARCHAR(40) NOT NULL,
  vendor_id CHAR(36) NULL,
  request_count INT UNSIGNED NOT NULL,
  window_days SMALLINT UNSIGNED NOT NULL DEFAULT 30,
  threshold_count SMALLINT UNSIGNED NOT NULL DEFAULT 3,
  status VARCHAR(24) NOT NULL DEFAULT 'open',
  vendor_note VARCHAR(2000) NULL,
  vendor_noted_at DATETIME NULL,
  admin_note VARCHAR(2000) NULL,
  admin_reviewed_by CHAR(36) NULL,
  admin_reviewed_at DATETIME NULL,
  last_return_id CHAR(36) NOT NULL,
  first_flagged_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  UNIQUE KEY uniq_return_review_scope (customer_id,scope_key),
  KEY idx_return_review_vendor (vendor_id,status,updated_at),
  KEY idx_return_review_status (status,updated_at),
  CONSTRAINT fk_return_review_customer FOREIGN KEY (customer_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_return_review_vendor FOREIGN KEY (vendor_id) REFERENCES vendors(id) ON DELETE CASCADE,
  CONSTRAINT fk_return_review_last_return FOREIGN KEY (last_return_id) REFERENCES return_requests(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
