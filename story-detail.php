      <p style="font-size:1.0625rem;color:var(--text-secondary);line-height:1.85;margin-bottom:20px;">I was twelve years old when my grandfather first let me touch the clay. Not mold it — just touch it. "Feel how it breathes," he said to me in Rajasthani. "The clay is alive. You must listen to it before you can shape it."</p>
      <p style="font-size:1.0625rem;color:var(--text-secondary);line-height:1.85;margin-bottom:20px;">That lesson has shaped my entire life. I am Rajan Kumhar, fourth-generation master of Jaipur Blue Pottery — one of the rarest craft traditions in the world. Our family migrated from Sindh (now Pakistan) three generations ago, carrying our Persian pottery techniques across the border. We settled in Jaipur's old city, in a neighborhood that once had over 200 pottery families.</p>

      <blockquote style="border-left:4px solid var(--saffron);padding:16px 20px;background:var(--saffron-pale);border-radius:0 var(--r-md) var(--r-md) 0;font-style:italic;font-size:1.125rem;color:var(--text-secondary);line-height:1.7;margin:28px 0;">
        "In 1990, there were only seven pottery families left in all of Jaipur. The plastic revolution had killed our market. My father nearly gave up."
      </blockquote>

      <p style="font-size:1.0625rem;color:var(--text-secondary);line-height:1.85;margin-bottom:20px;">Blue Pottery is unusual because it doesn't use clay from the earth. Instead, it's made from powdered quartz stone, glass, Multani mitti, borax, gum and water — no clay at all. This gives finished pieces their characteristic slightly translucent quality and that extraordinary blue-and-white sheen. But the formula is secret, passed only between masters and apprentices within families.</p>

      <p style="font-size:1.0625rem;color:var(--text-secondary);line-height:1.85;margin-bottom:20px;">The revival began in the 1970s when Maharani Gayatri Devi of Jaipur championed our craft. Then in the 1990s, when exports began, we finally had a market. By the 2000s, Jaipur Blue Pottery had global recognition — but the irony was that mass-produced Chinese imitations flooded the market at a fraction of our prices.</p>

      <p style="font-size:1.0625rem;color:var(--text-secondary);line-height:1.85;margin-bottom:0;">Platforms like Conscious India have become lifelines for authentic craftspeople. When someone buys one of my vases, they're not just buying pottery — they're buying four centuries of knowledge, the labor of my hands, and a vote for cultural preservation. That's worth every rupee of the price difference.</p>
